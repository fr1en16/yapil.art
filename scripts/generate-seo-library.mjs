function coverSvg({ slug, serviceIndex }) {
  const seed = hashInt(slug);
  const rand = (offset, min, max) => min + ((hashInt(`${seed}:${offset}`) % 10000) / 10000) * (max - min);
  const motif = ['M0 0H120V60H60V120H0Z', 'M0 0H120V120H70A70 70 0 0 1 0 50Z', 'M0 0H120V45H45V120H0Z', 'M0 0H120V120H0ZM35 35H85V85H35Z', 'M0 0H48V120H0ZM72 0H120V120H72Z', 'M0 0H120V34H34V120H0Z'][serviceIndex];
  const items = Array.from({ length: 18 }, (_, index) => {
    const x = rand(index * 7, 30, 1510);
    const y = rand(index * 7 + 1, 40, 760);
    const w = rand(index * 7 + 2, 45, 230);
    const h = rand(index * 7 + 3, 28, 190);
    const rotate = rand(index * 7 + 4, -8, 8);
    const fill = ['#FD4B32', '#171717', '#F7F5F2', '#80EFC9', '#D7D2CB'][index % 5];
    const stroke = index % 3 === 0 ? '#171717' : 'none';
    return `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" fill="${fill}" stroke="${stroke}" stroke-width="2" transform="rotate(${rotate.toFixed(1)} ${(x + w / 2).toFixed(1)} ${(y + h / 2).toFixed(1)})"/>`;
  }).join('');
  const rules = Array.from({ length: 8 }, (_, index) => `<line x1="${820 + index * 92}" y1="90" x2="${820 + index * 92}" y2="760" stroke="#171717" stroke-opacity=".22"/>`).join('');
  const chips = Array.from({ length: 5 }, (_, index) => `<rect x="${900 + index * 122}" y="620" width="100" height="68" fill="${['#FD4B32', '#171717', '#D7D2CB', '#F7F5F2', '#80EFC9'][index]}" stroke="#171717"/>`).join('');

  return `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="840" viewBox="0 0 1600 840">
    <defs>
      <filter id="shadow" x="-30%" y="-30%" width="160%" height="160%"><feDropShadow dx="0" dy="8" stdDeviation="7" flood-color="#171717" flood-opacity=".18"/></filter>
      <pattern id="grain" width="7" height="7" patternUnits="userSpaceOnUse"><circle cx="1" cy="1" r=".7" fill="#171717" opacity=".12"/></pattern>
      <clipPath id="photo"><rect x="180" y="150" width="330" height="300"/></clipPath>
    </defs>
    <rect width="1600" height="840" fill="#F7F5F2"/>
    <rect width="1600" height="840" fill="url(#grain)" opacity=".26"/>
    <g opacity=".24">${Array.from({ length: 13 }, (_, i) => `<line x1="${i * 133}" y1="0" x2="${i * 133}" y2="840" stroke="#171717"/>`).join('')}${Array.from({ length: 8 }, (_, i) => `<line x1="0" y1="${i * 120}" x2="1600" y2="${i * 120}" stroke="#171717"/>`).join('')}</g>
    <g filter="url(#shadow)">${items}</g>
    <g clip-path="url(#photo)"><rect x="180" y="150" width="330" height="300" fill="#CFCAC4"/><rect x="180" y="150" width="330" height="300" fill="url(#grain)" opacity=".9"/><path d="M160 420L340 190L530 370" fill="none" stroke="#171717" stroke-width="42" opacity=".55"/></g>
    <line x1="800" y1="35" x2="800" y2="805" stroke="#171717" stroke-width="2"/>${rules}
    <g transform="translate(${960 + (seed % 110)} ${170 + (seed % 60)}) scale(1.75)" filter="url(#shadow)"><path d="${motif}" fill="#FD4B32"/><path d="${motif}" fill="none" stroke="#171717" stroke-width="2" transform="translate(22 22)" opacity=".78"/></g>
    <g>${chips}</g>
    <rect x="835" y="90" width="700" height="620" fill="none" stroke="#171717" stroke-width="2"/>
  </svg>`;
}

async function writeCover(slug, serviceSlug, serviceIndex) {
  const dir = join(COVER_ROOT, serviceSlug);
  await mkdir(dir, { recursive: true });
  const path = join(dir, `${slug}.webp`);
  try {
    await access(path);
    return `/articles/covers/${serviceSlug}/${slug}.webp`;
  } catch {
    // Render only missing covers so interrupted batches can resume safely.
  }
  await sharp(Buffer.from(coverSvg({ slug, serviceIndex }))).webp({ quality: 86 }).toFile(path);
  return `/articles/covers/${serviceSlug}/${slug}.webp`;
}

async function updateExistingArticles() {
  for (const [serviceIndex, service] of services.entries()) {
    const dir = join(CONTENT_ROOT, service.slug);
    const files = (await readdir(dir)).filter((file) => file.endsWith('.md') && !file.startsWith('trend-'));
    for (const file of files) {
      const slug = file.replace(/\.md$/, '');
      const path = join(dir, file);
      let source = await readFile(path, 'utf8');
      const h1 = source.match(/^h1:\s*"([^"]+)"/m)?.[1] ?? slug;
      const cover = await writeCover(slug, service.slug, serviceIndex);
      const alt = `Редакционный коллаж Yapil о теме «${h1}»`;
      if (!/^cover:/m.test(source)) source = source.replace(/^status:/m, `cover: ${JSON.stringify(cover)}\ncoverAlt: ${JSON.stringify(alt)}\nstatus:`);
      await writeFile(path, source, 'utf8');
    }
  }
}

async function generateLibrary() {
  const manifest = [];
  for (const [serviceIndex, service] of services.entries()) {
    const dir = join(CONTENT_ROOT, service.slug);
    await mkdir(dir, { recursive: true });
    for (const cluster of service.clusters) {
      for (const angle of angles) {
        const slug = `trend-${cluster[0]}-${angle.slug}`;
        const h1 = articleTitle(cluster[1], angle);
        const title = seoTitle(cluster[1], angle);
        const cover = await writeCover(slug, service.slug, serviceIndex);
        const coverAlt = `Редакционный коллаж к статье «${h1}» в модульной визуальной системе Yapil`;
        const data = {
          title,
          description: seoDescription(cluster[1], angle),
          h1,
          service: service.name,
          primaryKeyword: `${cluster[1]} ${angle.label}`,
          searchIntent: angle.intent,
          relatedKeywords: cluster[2],
          author: 'Yapil',
          cover,
          coverAlt,
          trendCluster: cluster[0],
          trendBasis: 'Google Trends, Казахстан, последние 5 лет; редакционная кластеризация Yapil',
          status: 'draft',
        };
        const body = articleBody({ service, cluster, angle, related: cluster[2] });
        await writeFile(join(dir, `${slug}.md`), `${frontmatter(data)}${body}`, 'utf8');
        manifest.push({ slug, service: service.name, title: h1, seoTitle: title, cover, coverAlt, primaryKeyword: data.primaryKeyword, status: 'draft' });
      }
    }
  }
  await writeFile(join(CONTENT_ROOT, 'trend-library-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
}

await updateExistingArticles();
await generateLibrary();
console.log(`Generated ${services.length * 100} trend-based article drafts and covers.`);
